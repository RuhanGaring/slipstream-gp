// Minimum-time racing line. Starts from the minimum-curvature line and keeps any
// smooth lateral bump (Gaussian, 10 to 80 m wide) that lowers the lap time of the
// quasi-steady speed model, using the grip the AI learned for each circuit. This is
// what turns a geometric line into a racing line: later apexes before long
// straights, straighter braking, and lines that trade one corner for the next.
// Writes js/lines.js.   usage: node tools/optline.js [track|all] [iterations]
const fs = require('fs');
const path = require('path');
const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'limits.js', 'data.js', 'ai.js', 'race.js']);
const ids = process.argv[2] && process.argv[2] !== 'all' ? [process.argv[2]] : F1.Tracks.DEFS.map(d => d.id);
const ITERS = +process.argv[3] || 30000;
const STRIDE = 2;
const outFile = path.join(__dirname, '..', 'js', 'lines.js');
const prev = (globalThis.F1.Lines = {});
if (fs.existsSync(outFile)) { require('vm').runInThisContext(fs.readFileSync(outFile, 'utf8')); Object.assign(prev, globalThis.F1.Lines); }
const result = {};
for (const k of Object.keys(prev)) if (k !== 'stride') result[k] = prev[k];

for (const id of ids) {
  const def = F1.Tracks.byId(id);
  const tr = F1.Tracks.build(def);
  const N = tr.N;
  const lim = F1.Raceline.lineLimits(tr);
  const grip = F1.Race.learnedGrip(tr, 'sim');
  const evalT = off => {
    const line = F1.Raceline.lineFromOffsets(tr, off);
    let rough = 0; // a little smoothness so the line stays drivable
    for (let i = 0; i < N; i++) { const d2 = off[(i + 1) % N] - 2 * off[i] + off[(i - 1 + N) % N]; rough += d2 * d2; }
    return F1.Raceline.lapTime(tr, line, F1.Car.SPEC, { pace: 1, grip }) + rough * 0.02;
  };
  // seed: the driver's line (turn-in, late apex, track-out); compare with the geometric one
  const seeds = { technique: F1.Raceline.techniqueLine(tr), mincurv: F1.Raceline.computeLine(tr).off };
  const start = seeds[process.env.SEED || 'technique'];
  let off = Float64Array.from(start);
  let best = evalT(off);
  const t0 = best, rnd = F1.U.rng(7);
  const cand = new Float64Array(N);
  let accepted = 0;
  for (let it = 0; it < ITERS; it++) {
    const anneal = 1 - it / ITERS;
    const c = Math.floor(rnd() * N);
    const sig = (5 + rnd() * 35) / tr.ds * 2; // samples
    const amp = (rnd() - 0.5) * 2 * (0.3 + 2.2 * anneal);
    cand.set(off);
    const R = Math.ceil(sig * 3);
    for (let q = -R; q <= R; q++) {
      const i = (c + q + N) % N;
      cand[i] = lim.clamp(i, cand[i] + amp * Math.exp(-0.5 * (q / sig) ** 2));
    }
    const t = evalT(cand);
    if (t < best) { best = t; off.set(cand); accepted++; }
  }
  const st = F1.Raceline.straighten(tr, off, evalT); // no ripples or flicks a real car would not drive
  off = st.off; best = st.t;
  const out = [];
  for (let i = 0; i < N; i += STRIDE) out.push(+off[i].toFixed(2));
  result[id] = out;
  console.log(`${id}: model lap ${F1.U.fmtTime(t0)} -> ${F1.U.fmtTime(best)}  (${accepted} improvements)`);
}
let js = '// Generated by tools/optline.js: minimum-time racing line offsets per circuit,\n// stored every ' + STRIDE + ' samples. Do not edit by hand.\n';
js += '(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.Lines = { stride: ' + STRIDE + ',\n';
for (const id of Object.keys(result)) js += `    ${/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id)}: [${result[id].join(',')}],\n`;
js += '  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(outFile, js);
console.log('wrote', outFile);
