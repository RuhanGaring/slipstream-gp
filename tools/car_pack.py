"""Pack the converted cars (tools/car_prep26.mjs output in assets-src/cars) into script files,
so they load from file:// as well as from the web: js/assets/cars/ID.js holds one car file and
js/assets/cars/tex.js every texture, base64 encoded (js/carmodels.js decodes them).
usage: python tools/car_pack.py"""
import base64, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src, out = root / 'assets-src' / 'cars', root / 'js' / 'assets' / 'cars'
out.mkdir(parents=True, exist_ok=True)
for f in sorted(src.glob('*.car')):
    b = base64.b64encode(f.read_bytes()).decode()
    (out / (f.stem + '.js')).write_text(f"// Generated by tools/car_pack.py from tools/car_prep26.mjs output. See CREDITS.md.\n(function (G) {{ (G.F1.CarFiles = G.F1.CarFiles || {{}})['{f.stem}'] = '{b}'; }})(window);\n", encoding='utf-8')
tex = sorted((src / 'tex').glob('*.webp'))
lines = ',\n'.join(f"  '{t.name}': '{base64.b64encode(t.read_bytes()).decode()}'" for t in tex)
(out / 'tex.js').write_text(f"// Generated by tools/car_pack.py: the cars' textures (WebP). See CREDITS.md.\n(function (G) {{ G.F1.CarTex = {{\n{lines}\n}}; }})(window);\n", encoding='utf-8')
print('packed', len(list(src.glob('*.car'))), 'cars and', len(tex), 'textures, MB:', round(sum(p.stat().st_size for p in out.glob('*.js')) / 1048576, 1))
