// Takes the kinks out of the racing lines. A line from the optimiser can pinch to a few metres' radius
// at an apex, and the speed plan then drags the car down to walking pace for that one spot. Each
// tight spot is relaxed like a stretched elastic band, the car stays on the road, and the change is
// kept only if real laps in the game's physics are quicker overall, on race fuel and used tyres and
// on a fresh car alike, no worse in either, and no less clean than before.
// Runs on every thread the machine has.
// usage: node tools/unkink.js <track,track|all> [--list]   writes OUT/<track>.json (default tools/data/unkink)
//        node tools/unkink.js apply DIR                    stores the result in js/lines.js
const { Worker, isMainThread, workerData, parentPort } = require('worker_threads');
const fs = require('fs'), os = require('os'), path = require('path');
const LOAD = ['util.js', 'tracks.js', 'car.js', 'raceline.js', 'lines.js', 'limits.js', 'data.js', 'ai.js', 'race.js'], DT = 1 / 240;
const TIGHT = 28; // metres of radius: a line tighter than this is looked at
if (!isMainThread) {
  const F1 = require('./load')(LOAD);
  const race = F1.Race.create({ track: workerData.id, mode: 'tt', laps: 4, difficulty: 4, team: 0, driver: 0, seed: 7, field: 1, spectate: true, assists: {} });
  race.autoPlayer = true;
  const c = race.player, tr = race.track, E = F1.Raceline.lineLimits(tr);
  let race1 = true;
  const hold = () => { for (const w of c.wheels) w.wear = race1 ? 0.3 : 0; c.fuel = race1 ? 25 : 10; };
  const lap = (off, st) => {
    race1 = st;
    F1.Raceline.applyLine(tr, F1.Raceline.lineFromOffsets(tr, off));
    tr.rubber.fill(st ? 0.4 : 0.6);
    c.brain.prof = F1.Raceline.speedProfile(tr, tr.line, c.spec, F1.Race.planOpts(tr, true, 1));
    const n0 = c.lapTimes.length; let g = 0;
    while (c.lapTimes.length === n0 && g++ < 240 * 400) { hold(); F1.Race.step(race, DT); race.fx.length = 0; }
    const start = race.time, n1 = c.lapTimes.length; let bad = g >= 240 * 400 ? 1 : 0; g = 0;
    while (c.lapTimes.length === n1 && g++ < 240 * 400) {
      hold(); F1.Race.step(race, DT);
      for (const f of race.fx) if (f.type === 'wall' && f.power > 2) bad = 1;
      race.fx.length = 0;
      const i = c.loc.i;
      if (c.loc.d < -E.L[i] - 0.7 || c.loc.d > E.R[i] + 0.7 || (Math.abs(c.r) > 1.6 && c.speed > 20 && Math.abs(c.v) > 6) || c.brain.stuckT > 0.3) bad = 1;
    }
    return { t: race.time - start, bad: bad || g >= 240 * 400 ? 1 : 0 };
  };
  parentPort.on('message', m => parentPort.postMessage({ k: m.k, r: lap(Float64Array.from(m.off), m.st) }));
  parentPort.postMessage({ ready: true });
} else if (process.argv[2] === 'apply') {
  const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'lines.js']);
  const dir = process.argv[3], Ls = F1.Lines;
  for (const f of fs.readdirSync(dir)) { if (!f.endsWith('.json')) continue; const o = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); if (o.fixed) { Ls[o.id] = o.off.filter((_, i) => i % Ls.stride === 0); console.log(o.id, o.first.toFixed(3), '->', o.best.toFixed(3), o.fixed, 'kinks'); } }
  let a = '// Generated by tools/optline.js and tools/unkink.js: racing line offsets per circuit,\n// stored every 2 samples. Do not edit by hand.\n(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.Lines = { stride: ' + Ls.stride + ',\n';
  for (const id of Object.keys(Ls)) if (id !== 'stride') a += `    ${/^[a-z]\w*$/i.test(id) ? id : JSON.stringify(id)}: [${Array.from(Ls[id]).map(x => +x.toFixed(2)).join(',')}],\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'lines.js'), a + "  };\n})(typeof window !== 'undefined' ? window : globalThis);\n");
} else {
  const F1 = require('./load')(LOAD);
  const ids = !process.argv[2] || process.argv[2] === 'all' ? F1.Tracks.DEFS.map(d => d.id) : process.argv[2].split(',');
  const list = process.argv.includes('--list'), OUT = process.env.OUT || path.join(__dirname, 'data', 'unkink'), NT = Math.max(2, os.cpus().length - 1);
  fs.mkdirSync(OUT, { recursive: true });
  // the groups of samples tighter than TIGHT
  const findKinks = (tr, kap) => {
    const N = tr.N, out = []; let cur = null;
    for (let i = 0; i < N; i++) {
      if (Math.abs(kap[i]) > 1 / TIGHT) { if (cur && i - cur.b <= 4) cur.b = i; else { cur = { a: i, b: i }; out.push(cur); } if (Math.abs(kap[i]) > (cur.pk || 0)) { cur.pk = Math.abs(kap[i]); cur.at = i; } }
    }
    return out;
  };
  // an elastic band over the stretch of road: each point moves toward the middle of its neighbours,
  // along the road's normal, staying inside the corridor the car may use
  const relax = (tr, E, off0, a, b, W, its) => {
    const N = tr.N, off = Float64Array.from(off0), w = Math.round(W / tr.ds), q = i => (i + N * 2) % N, step = 3;
    for (let it = 0; it < its; it++) for (let k = a - w; k <= b + w; k++) {
      const i = q(k), p = q(k - step), n = q(k + step), mask = Math.min(1, Math.min(k - (a - w), (b + w) - k) / (w * 0.5 + 1));
      const px = tr.x[i] + tr.nx[i] * off[i], py = tr.y[i] + tr.ny[i] * off[i];
      const mx = (tr.x[p] + tr.nx[p] * off[p] + tr.x[n] + tr.nx[n] * off[n]) / 2, my = (tr.y[p] + tr.ny[p] * off[p] + tr.y[n] + tr.ny[n] * off[n]) / 2;
      off[i] = Math.max(-E.L[i] + 0.05, Math.min(E.R[i] - 0.05, off[i] + mask * 0.5 * ((mx - px) * tr.nx[i] + (my - py) * tr.ny[i])));
    }
    return off;
  };
  const one = async id => {
    const tr = F1.Race.getTrack(id), E = F1.Raceline.lineLimits(tr), kinks = findKinks(tr, tr.line.kap);
    console.log(id, kinks.length, 'tight spots:', kinks.map(k => `${Math.round(k.at * tr.ds)}m r${(1 / k.pk).toFixed(0)}`).join(' '));
    if (list || !kinks.length) return;
    const ws = await Promise.all(Array.from({ length: NT }, () => new Promise(res => { const w = new Worker(__filename, { workerData: { id } }); w.once('message', () => res(w)); })));
    let seq = 0;
    const free = ws.slice(), wait = [];
    const use = async job => { const w = free.pop() || await new Promise(r => wait.push(r)); try { return await job(w); } finally { const q = wait.shift(); if (q) q(w); else free.push(w); } };
    const call = (off, st) => use(w => new Promise(res => { const k = ++seq, f = m => { if (m.k === k) { w.off('message', f); res(m.r); } }; w.on('message', f); w.postMessage({ k, off: Array.from(off), st }); }));
    const both = async off => { const [a, b] = await Promise.all([call(off, true), call(off, false)]); return { tR: a.t, tF: b.t, t: a.t + b.t, bad: a.bad + b.bad }; };
    const judge = async off => { const rs = (await Promise.all([both(off), both(off), both(off)])).sort((a, b) => a.t - b.t); return Object.assign(rs[1], { bad: Math.max(...rs.map(r => r.bad)) }); };
    let off = Float64Array.from(tr.line.off); await judge(off); let base = await judge(off), fixed = 0; const first = base.t;
    console.log(' base race', base.tR.toFixed(3), 'fresh', base.tF.toFixed(3), 'bad', base.bad);
    for (const k of kinks) {
      // several sizes of change tried side by side on all threads
      const cands = []; for (const W of [14, 26, 40]) for (const its of [12, 40, 110]) cands.push(relax(tr, E, off, k.a, k.b, W, its));
      const rs = await Promise.all(cands.map(async (o, c) => ({ c, r: await both(o) })));
      const best = rs.filter(x => x.r.bad <= base.bad && x.r.tR < base.tR + 0.05 && x.r.tF < base.tF + 0.05).sort((a, b) => a.r.t - b.r.t)[0];
      if (!best || best.r.t > base.t - 0.03) { console.log(`  ${Math.round(k.at * tr.ds)}m no gain`); continue; }
      const check = await judge(cands[best.c]);
      if (check.t < base.t - 0.02 && check.bad <= base.bad && check.tR < base.tR + 0.05 && check.tF < base.tF + 0.05) { off = cands[best.c]; console.log(`  ${Math.round(k.at * tr.ds)}m race ${base.tR.toFixed(3)} -> ${check.tR.toFixed(3)}  fresh ${base.tF.toFixed(3)} -> ${check.tF.toFixed(3)}`); base = check; fixed++; } else console.log(`  ${Math.round(k.at * tr.ds)}m did not repeat`);
    }
    await Promise.all(ws.map(w => w.terminate()));
    fs.writeFileSync(path.join(OUT, id + '.json'), JSON.stringify({ id, first: first / 2, best: base.t / 2, fixed, off: Array.from(off, x => +x.toFixed(3)) }));
    console.log(`DONE ${id} ${(first / 2).toFixed(3)} -> ${(base.t / 2).toFixed(3)} average of both (${fixed} of ${kinks.length})`);
  };
  (async () => { for (const id of ids) await one(id); process.exit(0); })();
}
