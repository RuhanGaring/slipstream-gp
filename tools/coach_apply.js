// Stores what tools/coach.js found into js/limits.js: the coached corner grip as the circuit's sim
// limits, and its braking grip beside them as simB. A coached circuit then drives this plan flat out.
// usage: node tools/coach_apply.js DIR [track,track]
const fs = require('fs'), path = require('path');
const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'lines.js', 'limits.js']);
const dir = process.argv[2], only = process.argv[3] ? process.argv[3].split(',') : null;
const L = F1.Limits, st = L.stride, out = path.join(__dirname, '..', 'js', 'limits.js');
for (const f of fs.readdirSync(dir)) {
  if (!f.endsWith('.json')) continue;
  const o = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  if ((only && !only.includes(o.id)) || !L[o.id]) continue;
  const pick = a => a.filter((_, i) => i % st === 0);
  L[o.id].sim = pick(o.g); L[o.id].simB = pick(o.gB); L[o.id].simLap = [+o.best.toFixed(3)];
  console.log(o.id, o.first.toFixed(3), '->', o.best.toFixed(3));
}
let s = "// Generated by tools/learn.js and tools/coach.js: per-circuit grip multipliers the AI has learned it\n// can use, stored every 5 samples (10 m). sim and simB, where a circuit has both, are the plan the\n// coach found fastest, for corners and for braking. Do not edit by hand.\n(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.Limits = { stride: " + st + ",\n";
for (const id of Object.keys(L)) {
  if (id === 'stride') continue;
  s += `    ${/^[a-z]\w*$/i.test(id) ? id : JSON.stringify(id)}: {\n`;
  for (const k of Object.keys(L[id])) s += `      ${k}: [${Array.from(L[id][k]).join(',')}],\n`;
  s += '    },\n';
}
s += '  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(out, s);
