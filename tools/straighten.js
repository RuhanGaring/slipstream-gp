// Runs the racing-line straightening pass (Raceline.straighten) over the stored lines in
// js/lines.js: removes ripples and sudden flicks the optimiser left without changing
// the line's shape. Relearn the limits afterwards.   usage: node tools/straighten.js [track|all]
const fs = require('fs');
const path = require('path');
const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'lines.js', 'limits.js', 'data.js', 'ai.js', 'race.js']);
const ids = process.argv[2] && process.argv[2] !== 'all' ? [process.argv[2]] : F1.Tracks.DEFS.map(d => d.id);
const STRIDE = F1.Lines.stride;
for (const id of ids) {
  const tr = F1.Race.getTrack(id), grip = F1.Race.learnedGrip(tr, 'sim');
  const evalT = off => F1.Raceline.lapTime(tr, F1.Raceline.lineFromOffsets(tr, off), F1.Car.SPEC, { pace: 1, grip });
  const t0 = evalT(tr.line.off);
  const st = F1.Raceline.straighten(tr, tr.line.off, evalT);
  const out = [];
  for (let i = 0; i < tr.N; i += STRIDE) out.push(+st.off[i].toFixed(2));
  F1.Lines[id] = out;
  console.log(`${id}: model lap ${F1.U.fmtTime(t0)} -> ${F1.U.fmtTime(st.t)}`);
}
let js = '// Generated by tools/optline.js: minimum-time racing line offsets per circuit,\n// stored every ' + STRIDE + ' samples. Do not edit by hand.\n';
js += '(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.Lines = { stride: ' + STRIDE + ',\n';
for (const id of Object.keys(F1.Lines)) if (id !== 'stride') js += `    ${/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id)}: [${F1.Lines[id].join(',')}],\n`;
js += '  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'lines.js'), js);
console.log('wrote js/lines.js');
