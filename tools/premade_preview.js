// The menu's picture of each premade generated circuit (js/premade.js): enough of the built track
// to draw its map and list its stats, so the circuit list does not build a whole town just to
// show a thumbnail.   usage: node tools/premade_preview.js
const fs = require('fs');
const path = require('path');
const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'lines.js', 'limits.js', 'data.js', 'ai.js', 'race.js']);
const round = (a, k) => Array.from(a, v => +v.toFixed(k));
let js = '// Generated by tools/premade_preview.js: what the menus show of the premade generated circuits.\n(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.Premade = {\n';
for (const d of F1.Tracks.DEFS) {
  if (!d.fixed) continue;
  const tr = F1.Race.getTrack(d.id);
  const lite = { N: tr.N, ds: tr.ds, L: tr.L, x: round(tr.x, 1), y: round(tr.y, 1), tx: round(tr.tx, 3), ty: round(tr.ty, 3), nx: round(tr.nx, 3), ny: round(tr.ny, 3), sectors: tr.sectors, drs: tr.drs, apexes: tr.apexes };
  js += `    ${d.id}: ${JSON.stringify(lite)},\n`;
  console.log(d.id, (tr.L / 1000).toFixed(3), 'km', tr.apexes.length, 'corners', tr.drs.length, 'zones');
}
js += "  };\n})(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(__dirname, '..', 'js', 'premade.js'), js);
