// Teaches the AI's live learning (js/race.js THINK: pace and line per 10 m) on the game's own circuits
// before it ships: a Legend car alone, look-ahead on, for LAPS laps per circuit, every circuit on its
// own worker thread. Writes js/aimem.js, which the races start from (a circuit not in it starts from
// its plan, and learns as it races).
//   node tools/aimem.js [laps] [ids comma-separated]
const { Worker, isMainThread, workerData, parentPort } = require('worker_threads');
const path = require('path'), fs = require('fs'), os = require('os');
if (!isMainThread) {
  const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'damage.js', 'softbody.js', 'raceline.js', 'lines.js', 'limits.js', 'premade.js', 'data.js', 'ai.js', 'race.js']);
  const { id, laps } = workerData, DT = 1 / 240;
  F1.AIMem = {}; // (from scratch)
  const race = F1.Race.create({ track: id, mode: 'tt', laps: 999, difficulty: 4, team: 0, driver: 0, seed: 7, field: 1, spectate: true, assists: {} });
  race.autoPlayer = true;
  const c = race.player, tr = race.track, b = c.brain;
  const hold = () => { for (const w of c.wheels) w.wear = 0; c.fuel = 10; tr.rubber.fill(0.6); };
  let g = 0, walls = 0, lastW = -9;
  while (c.lapTimes.length < laps && g++ < 240 * 400 * laps) {
    hold(); F1.Race.step(race, DT);
    for (const f of race.fx) if (f.type === 'wall' && race.time - lastW > 1) { walls++; lastW = race.time; }
    race.fx.length = 0;
    if (c.lapTimes.length && g % 2400 === 0) parentPort.postMessage({ id, progress: c.lapTimes.length / laps });
  }
  const t = c.lapTimes.slice(1).map(l => l.t);
  parentPort.postMessage({ id, done: true, laps: t, walls, pace: Array.from(b.paceBest || b.paceMem, x => +x.toFixed(4)), line: Array.from(b.lineBest || b.lineMem, x => +x.toFixed(3)) });
} else {
  const F1 = require('./load')(['util.js', 'tracks.js', 'car.js', 'raceline.js', 'data.js', 'ai.js', 'race.js']);
  const laps = +(process.argv[2] || 10);
  const ids = process.argv[3] ? process.argv[3].split(',') : F1.Tracks.DEFS.map(d => d.id);
  const file = path.join(__dirname, '..', 'js', 'aimem.js');
  const out = {};
  try { const old = fs.readFileSync(file, 'utf8'); const m = /F1\.AIMem = (\{[\s\S]*\});/.exec(old); if (m) Object.assign(out, JSON.parse(m[1])); } catch (e) { /* first run */ }
  const prog = {}, t0 = Date.now(), NT = Math.max(1, os.cpus().length - 1);
  const bar = () => {
    const p = ids.reduce((a, id) => a + (prog[id] || 0), 0) / ids.length, el = (Date.now() - t0) / 1000;
    process.stdout.write(`\r[${'#'.repeat(Math.round(p * 30)).padEnd(30, '.')}] ${(p * 100).toFixed(0)}%  ${Math.floor(el / 60)}m${String(Math.round(el % 60)).padStart(2, '0')}s, about ${p > 0.02 ? Math.ceil(el / p * (1 - p) / 60) : '?'} min left `);
  };
  let next = 0, running = 0, done = 0;
  const launch = () => {
    while (running < NT && next < ids.length) {
      const id = ids[next++]; running++;
      const w = new Worker(__filename, { workerData: { id, laps } });
      w.on('message', m => {
        if (m.progress != null) { prog[id] = m.progress; bar(); return; }
        prog[id] = 1;
        out[id] = { pace: m.pace, line: m.line };
        console.log(`\n${id}: laps ${m.laps.map(x => x.toFixed(2)).join(' ')}  walls ${m.walls}`);
      });
      w.on('exit', () => { running--; done++; bar(); if (done === ids.length) write(); else launch(); });
      w.on('error', e => console.error('\n' + id + ': ' + e.message));
    }
  };
  const write = () => {
    fs.writeFileSync(file, '// Generated by tools/aimem.js: the AI\'s learned pace factor and line shift (metres toward the\n// inside of the bend) per 10 m of each circuit, from look-ahead practice. Do not edit by hand.\n(function (G) {\n  G.F1 = G.F1 || {};\n  G.F1.AIMem = ' + JSON.stringify(out) + ';\n})(typeof self !== \'undefined\' ? self : this);\n');
    console.log('\nwrote ' + file);
  };
  bar(); launch();
}
